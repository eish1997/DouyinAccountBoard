const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const context={document:{addEventListener(){}},data:{today:'2026-10-15',accounts:[]},$(){return {value:''};}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../static/phone-cards.js'),'utf8'),context);
const account=(kind,extra={})=>({registration_phone:'13800000000',account_type:kind,status:'正常',card_stability:'已稳定',password_state:'已修改',...extra});
const ready=accounts=>{context.data.accounts=accounts;return context.cardReady({phone:'13800000000'});};
assert.equal(ready([account('大号'),account('小号')]),true);
assert.equal(ready([account('大号',{status:'封禁',card_stability:'待确认',password_state:'待确认'}),account('小号')]),true);
assert.equal(ready([account('大号'),account('小号',{password_state:'未修改'})]),false);
assert.equal(ready([account('大号'),account('小号',{card_stability:'未稳定'})]),false);
assert.equal(ready([account('大号')]),false);
assert.equal(ready([account('待确认'),account('小号')]),false);
assert.equal(ready([account('大号'),account('大号'),account('小号')]),false);
assert.equal(ready([account('大号',{status:'封禁'}),account('小号',{status:'封禁'})]),false);
assert.equal(ready([]),false);
assert.equal(context.cardExpiring({expires_on:'2026-10-22'}),true);
assert.equal(context.cardExpiring({expires_on:'2026-10-23'}),false);
console.log('手机卡：大小号稳定改密、大号封禁小号稳定、未知关系与到期边界测试通过');
